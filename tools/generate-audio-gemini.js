#!/usr/bin/env node
/* the killer tv — build the narration pack with Gemini TTS.
 *
 *   set GEMINI_API_KEY=...        (Windows cmd)
 *   $env:GEMINI_API_KEY="..."     (PowerShell)
 *   export GEMINI_API_KEY=...     (bash)
 *
 *   node tools/generate-audio-gemini.js
 *
 * Same thing Google's Python sample does, over plain REST so there is nothing
 * to pip install. Gemini returns raw PCM with the format in the mime type, so
 * each clip gets a WAV header bolted on here. If ffmpeg is on PATH the WAVs are
 * converted down to MP3 afterwards, because 72 WAVs is about 25 MB and 72 MP3s
 * is about 2.
 *
 * Options
 *   --voice <name>   default Charon. Others: Enceladus, Algenib, Gacrux,
 *                    Rasalgethi, Sadaltager, Zephyr, Kore, Puck…
 *   --model <id>     default gemini-3.1-flash-tts-preview
 *   --style "..."    the delivery note prepended to every line
 *   --only a,b,c     just these line ids
 *   --force          regenerate clips that already exist
 *   --keep-wav       skip the MP3 conversion
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'audio');

const arg = (name, fallback) => {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const has = (name) => process.argv.includes('--' + name);

const KEY = (process.env.GEMINI_API_KEY || process.env.GOOGLE_TTS_KEY || '')
  .trim().replace(/^["']|["']$/g, '');
const MODEL = arg('model', 'gemini-3.1-flash-tts-preview');
const VOICE = arg('voice', 'Charon');
const STYLE = arg('style',
  'Read this as a British narrator for a horror party game. Deep, low and unhurried. ' +
  'Grim but matter-of-fact, never shouting and never whispering:');

function loadLines() {
  const src = fs.readFileSync(path.join(ROOT, 'js', 'lines.js'), 'utf8');
  const box = {};
  const body = src
    .replace(/^const LINES/m, 'box.LINES')
    .replace(/^const LINE_IDS[\s\S]*$/m, '');
  new Function('box', body)(box);
  return box.LINES;
}

function parsePcmMime(mime) {
  const rate = Number((/rate=(\d+)/.exec(mime || '') || [])[1] || 24000);
  const bits = Number((/audio\/L(\d+)/.exec(mime || '') || [])[1] || 16);
  return { rate, bits };
}

function toWav(pcm, sampleRate, bitsPerSample) {
  const channels = 1;
  const bits = bitsPerSample || 16;
  const blockAlign = channels * (bits / 8);
  const head = Buffer.alloc(44);
  head.write('RIFF', 0);
  head.writeUInt32LE(36 + pcm.length, 4);
  head.write('WAVE', 8);
  head.write('fmt ', 12);
  head.writeUInt32LE(16, 16);
  head.writeUInt16LE(1, 20);
  head.writeUInt16LE(channels, 22);
  head.writeUInt32LE(sampleRate, 24);
  head.writeUInt32LE(sampleRate * blockAlign, 28);
  head.writeUInt16LE(blockAlign, 32);
  head.writeUInt16LE(bits, 34);
  head.write('data', 36);
  head.writeUInt32LE(pcm.length, 40);
  return Buffer.concat([head, pcm]);
}

async function synth(text) {
  const url = 'https://generativelanguage.googleapis.com/v1beta/models/' +
    encodeURIComponent(MODEL) + ':generateContent?key=' + encodeURIComponent(KEY);

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ role: 'user', parts: [{ text: STYLE + '\n\n## Transcript:\n' + text }] }],
      generationConfig: {
        temperature: 1,
        responseModalities: ['audio'],
        speechConfig: {
          voiceConfig: { prebuiltVoiceConfig: { voiceName: VOICE } },
        },
      },
    }),
  });

  if (!res.ok) throw new Error(res.status + ' ' + (await res.text()).slice(0, 400));

  const json = await res.json();
  const part = json.candidates && json.candidates[0] && json.candidates[0].content &&
    json.candidates[0].content.parts && json.candidates[0].content.parts[0];
  const inline = part && part.inlineData;
  if (!inline || !inline.data) throw new Error('no audio in the response');

  const raw = Buffer.from(inline.data, 'base64');
  if (raw.slice(0, 4).toString() === 'RIFF') return raw;
  const fmt = parsePcmMime(inline.mimeType);
  return toWav(raw, fmt.rate, fmt.bits);
}

function haveFfmpeg() {
  try { execFileSync('ffmpeg', ['-version'], { stdio: 'ignore' }); return true; }
  catch (e) { return false; }
}

function writeManifest(lines, ext) {
  const present = Object.keys(lines).filter((id) => fs.existsSync(path.join(OUT, id + ext)));
  fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify({
    note: 'Generated by tools/generate-audio-gemini.js.',
    format: ext.replace('.', ''),
    voice: VOICE + ' (' + MODEL + ')',
    lines: present,
  }, null, 2) + '\n');
  return present.length;
}

async function main() {
  if (!KEY) {
    console.error('GEMINI_API_KEY is not set. Get one at https://aistudio.google.com/apikey');
    process.exit(1);
  }

  const lines = loadLines();
  fs.mkdirSync(OUT, { recursive: true });

  const only = arg('only', '');
  let ids = Object.keys(lines);
  if (only) {
    const want = only.split(',').map((s) => s.trim());
    ids = ids.filter((id) => want.includes(id));
  }

  const mp3 = !has('keep-wav') && haveFfmpeg();
  const ext = mp3 ? '.mp3' : '.wav';
  console.log(MODEL + ' · voice ' + VOICE + ' · writing ' + ext.slice(1).toUpperCase());
  if (!mp3 && !has('keep-wav')) console.log('(ffmpeg not found, keeping WAV — larger files)');
  console.log(ids.length + ' line(s) to consider\n');

  let made = 0, skipped = 0, failed = 0;
  for (const id of ids) {
    const target = path.join(OUT, id + ext);
    if (fs.existsSync(target) && !has('force')) { skipped++; continue; }
    try {
      const wav = await synth(lines[id]);
      if (mp3) {
        const tmp = path.join(OUT, id + '.tmp.wav');
        fs.writeFileSync(tmp, wav);
        execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', tmp,
          '-af', 'loudnorm=I=-17:TP=-2', '-ac', '1', '-b:a', '64k', target]);
        fs.unlinkSync(tmp);
      } else {
        fs.writeFileSync(target, wav);
      }
      made++;
      console.log('  ok  ' + id.padEnd(22) + Math.round(fs.statSync(target).size / 1024) + ' kB');
    } catch (err) {
      failed++;
      console.error('  ✗   ' + id + ' — ' + err.message);
      // a bad key or a missing model fails identically for all 72; don't hammer it
      if (/API_KEY_INVALID|API key not valid|NOT_FOUND|PERMISSION_DENIED/i.test(err.message)) {
        console.error('\nStopping — that looks like a key or model problem, not a one-off.');
        break;
      }
    }
    await new Promise((r) => setTimeout(r, 200));
  }

  const total = writeManifest(lines, ext);
  console.log('\n' + made + ' written, ' + skipped + ' already there, ' + failed + ' failed');
  console.log('manifest lists ' + total + ' of ' + Object.keys(lines).length + ' lines');
}

main().catch((e) => { console.error(e); process.exit(1); });
